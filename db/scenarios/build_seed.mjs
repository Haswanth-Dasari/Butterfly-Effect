#!/usr/bin/env node
// Turns a scenario's content file (slice.json) into SQL seed rows: story tables + RULES.
// The story is data: running this is the only "compile" step, and the generated SQL is committed.
//   node db/scenarios/build_seed.mjs mystery      ->  db/seed/05_story_mystery.sql
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const key = process.argv[2] || 'mystery';
const S = JSON.parse(fs.readFileSync(path.join(here, key, 'slice.json'), 'utf8'));
const PROT = S.scenario.protagonist_id;

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const j = (o) => q(JSON.stringify(o));
const arr = (a) => (a.length ? `ARRAY[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const out = [];
const emit = (s) => out.push(s);

emit(`-- GENERATED by db/scenarios/build_seed.mjs from db/scenarios/${key}/slice.json. Do not edit by hand.`);
emit(`-- Applied separately from the core seed (db/seed/_seed_story.sql) so the core test suites stay exact.\n`);
emit(`INSERT INTO action_type (action_type, description) VALUES
('story_start', 'Story: a playthrough begins'),
('story_choice', 'Story: the protagonist makes a choice in a scene'),
('story_event', 'Story: something happens in the village'),
('story_enter', 'Story: a character enters the village'),
('discover', 'Story: the protagonist discovers a clue');\n`);

// new characters (they get a state row only when the story brings them in)
emit(`INSERT INTO actor (actor_id, name, kind, job, home_id) VALUES`);
emit(S.actors.map((a) => `(${a.id}, ${q(a.name)}, 'villager', ${q(a.job)}, NULL)`).join(',\n') + ';');
emit(`SELECT setval(pg_get_serial_sequence('actor', 'actor_id'), (SELECT max(actor_id) FROM actor));\n`);

const sc = S.scenario;
emit(`INSERT INTO scenario (scenario_key, title, tagline, genre, protagonist_id, slice_end_day) VALUES
(${q(sc.key)}, ${q(sc.title)}, ${q(sc.tagline)}, ${q(sc.genre)}, ${sc.protagonist_id}, ${sc.slice_end_day});\n`);

emit(`INSERT INTO case_link (link_key, scenario_key, title, question, ord) VALUES`);
emit(S.links.map((l, i) => `(${q(l.key)}, ${q(sc.key)}, ${q(l.title)}, ${q(l.question)}, ${i + 1})`).join(',\n') + ';\n');

emit(`INSERT INTO clue (clue_key, scenario_key, title, kind, day, journal) VALUES`);
emit(S.clues.map((c) => `(${q(c.key)}, ${q(sc.key)}, ${q(c.title)}, ${q(c.kind)}, ${c.day}, ${q(c.journal)})`).join(',\n') + ';\n');
const cl = S.clues.flatMap((c) => Object.entries(c.links).map(([l, w]) => `(${q(c.key)}, ${q(l)}, ${w})`));
if (cl.length) emit(`INSERT INTO clue_link (clue_key, link_key, weight) VALUES\n${cl.join(',\n')};\n`);

emit(`INSERT INTO story_day (scenario_key, day, title, intro) VALUES`);
emit(S.days.map((d) => `(${q(sc.key)}, ${d.day}, ${q(d.title)}, ${q(d.intro)})`).join(',\n') + ';\n');

emit(`INSERT INTO story_beat (beat_key, scenario_key, day, phase, ord, title, body, costs_action, max_picks, requires_beats, forbids_beats) VALUES`);
emit(S.beats.map((b, i) => `(${q(b.key)}, ${q(sc.key)}, ${b.day}, ${q(b.phase)}, ${i}, ${q(b.title)}, ${q(b.body)}, ${b.cost ? 'TRUE' : 'FALSE'}, ${b.max_picks}, ${arr(b.requires)}, ${arr(b.forbids)})`).join(',\n') + ';\n');

emit(`INSERT INTO story_option (beat_key, option_key, label, result_text, ord) VALUES`);
emit(S.beats.flatMap((b) => b.options.map((o, i) => `(${q(b.key)}, ${q(o.key)}, ${q(o.label)}, ${q(o.result)}, ${i})`)).join(',\n') + ';\n');

if (S.endings?.length) {
  emit(`INSERT INTO story_ending (scenario_key, ending_key, title, text, flag) VALUES`);
  emit(S.endings.map((e) => `(${q(sc.key)}, ${q(e.key)}, ${q(e.title)}, ${q(e.text)}, ${q(e.flag)})`).join(',\n') + ';\n');
}

// ---------------- rules ----------------
const rules = [];
const ent = (e) => (e === 'player' ? PROT : e);
function condFrom(base, when) {
  const c = { ...base };
  for (const [k, v] of Object.entries(when || {})) {
    if (k === 'state_lt' || k === 'state_gte') c[k] = { entity_id: PROT, key: v.key, value: v.value };
    else c[k] = v;
  }
  return c;
}
function effectFromOp(op) {
  if (op.discover) return { action: 'discover', actor: PROT, payload: { clue: op.discover }, visibility: 'private' };
  if (op.enter) {
    const a = S.actors.find((x) => x.id === op.enter);
    return { action: 'story_enter', actor: null, payload: { entity_id: a.id, state: a.state }, visibility: 'private' };
  }
  if (op.event) {
    const e = op.event; const payload = { kind: e.kind, text: e.text };
    if (e.target) payload.target_actor = e.target;
    return { action: 'story_event', actor: e.actor ?? null, payload, visibility: e.visibility || 'private' };
  }
  const payload = { entity_id: ent(op.entity) };
  if (op.set) payload.set = op.set;
  if (op.add) payload.add = op.add;
  return { action: 'state_change', actor: null, payload, visibility: 'private' };
}
const pushRule = (trigger, cond, op) => rules.push({ trigger, cond, eff: effectFromOp(op), why: op.why || null });

// story_start: base state first, then trait bonuses
rules.push({ trigger: 'story_start', cond: null, eff: effectFromOp({ entity: 'player', set: sc.start_state }), why: null });
for (const r of S.start_rules || []) for (const op of r.effects) pushRule('story_start', condFrom({}, r.when), op);

// day events (public text + effects)
for (const de of S.day_events) {
  const base = { scenario: sc.key, payload_eq: { day: de.day } };
  if (de.text) {
    rules.push({ trigger: 'day_start', cond: base, why: null,
      eff: { action: 'story_event', actor: null, payload: { kind: de.kind || 'event', text: de.text }, visibility: de.visibility === 'public' ? 'public' : 'private' } });
  }
  for (const op of de.effects || []) pushRule('day_start', condFrom(base, op.when), op);
}

// option effects
for (const b of S.beats) for (const o of b.options) for (const op of o.effects) {
  pushRule('story_choice', condFrom({ payload_eq: { beat: b.key, option: o.key } }, op.when), op);
}
// global story rules (e.g. death), emitted AFTER option effects so they see updated state
for (const r of S.rules || []) for (const op of r.effects) {
  const c = {};
  for (const [k, v] of Object.entries(r.when)) c[k] = k.startsWith('state_') ? { entity_id: PROT, key: v.key, value: v.value } : v;
  rules.push({ trigger: r.trigger, cond: c, eff: effectFromOp(op), why: r.why || op.why || null });
}

emit(`INSERT INTO rule (trigger_action_type, condition, effect_template, narrative_template, delay_ticks) VALUES`);
emit(rules.map((r) => `(${q(r.trigger)}, ${r.cond ? j(r.cond) : 'NULL'}, ${j(r.eff)}, ${q(r.why)}, 0)`).join(',\n') + ';\n');

const file = path.resolve(here, `../seed/05_story_${key}.sql`);
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${path.relative(process.cwd(), file)}: ${S.beats.length} beats, ${S.beats.reduce((n, b) => n + b.options.length, 0)} options, ${S.clues.length} clues, ${rules.length} rules`);
